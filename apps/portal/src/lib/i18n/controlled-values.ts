export function translateControlledValue(
  locale: PortalLocale,
  domain: ControlledValueDomain,
  value: string | null | undefined,
): string {
  if (!value) return '';
  const key = controlledKeys[domain][value] ?? controlledKeys[domain][value.toLowerCase()];
  return key ? translate(locale, key) : value;
}

export function hasControlledValue(domain: ControlledValueDomain, value: string): boolean {
  return Boolean(controlledKeys[domain][value] ?? controlledKeys[domain][value.toLowerCase()]);
}
