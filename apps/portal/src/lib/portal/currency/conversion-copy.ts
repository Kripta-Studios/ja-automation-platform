const copies = { en, es, pt } as const;

export function conversionText(
  locale: string,
  key: Key,
  params: Record<string, string | number> = {},
): string {
  const table = copies[(locale === 'es' || locale === 'pt' ? locale : 'en') as ConversionLocale];
  return table[key].replace(/\{(\w+)\}/gu, (_, name: string) => String(params[name] ?? ''));
}
