export type HomeCopyKey = keyof (typeof homeCopy)['en'];

export function homeText(
  locale: 'en' | 'es' | 'pt',
  key: HomeCopyKey,
  params: Readonly<Record<string, string | number>> = {},
): string {
  const value: string = homeCopy[locale]?.[key] ?? homeCopy.en[key];
  return value.replace(/\{(\w+)\}/gu, (_, name: string) => String(params[name] ?? `{${name}}`));
}
