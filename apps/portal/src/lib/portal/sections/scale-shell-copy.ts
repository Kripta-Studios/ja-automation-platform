const catalogs: Record<PortalLocale, Copy> = { en, es, pt };

export type ScaleShellCopyKey = keyof typeof en;

export function scaleCopy(
  locale: PortalLocale,
  key: ScaleShellCopyKey,
  params: Record<string, string | number> = {},
): string {
  const template = (catalogs[locale] ?? en)[key] ?? en[key];
  return template.replace(/\{(\w+)\}/gu, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

export const scaleLocaleTag: Record<PortalLocale, string> = {
  en: 'en-US',
  es: 'es-ES',
  pt: 'pt-BR',
};
