-- Optional contact facts are kept outside the immutable user/account identity.
-- Supplier and technician history remains linked to the same canonical user id.
CREATE TABLE supplier_contact_directory(
  user_id TEXT PRIMARY KEY REFERENCES user(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  phone TEXT CHECK(phone IS NULL OR length(trim(phone)) BETWEEN 1 AND 80),
  company TEXT CHECK(company IS NULL OR length(trim(company)) BETWEEN 1 AND 200),
  contact_name TEXT CHECK(contact_name IS NULL OR length(trim(contact_name)) BETWEEN 1 AND 160),
  notes TEXT CHECK(notes IS NULL OR length(notes)<=5000),
  updated_at TEXT NOT NULL,
  updated_by TEXT NOT NULL REFERENCES user(id) ON UPDATE RESTRICT ON DELETE RESTRICT
) STRICT;
CREATE INDEX supplier_contact_directory_company_idx ON supplier_contact_directory(company);

